/** I 18 tipi. */
export const ALL_TYPES = Object.keys(CHART) as PokeType[];

/** Efficacia vera dei giochi (×2, ×0.5, ×0…), non attenuata. */
export function effectiveness(attack: PokeType, defend: PokeType[]): number {
  return defend.reduce((m, d) => m * (CHART[attack]?.[d] ?? 1), 1);
}

/**
 * Vantaggio di tipo attenuato per il calcio: il miglior tipo dell'attaccante conta,
 * ma ×2 diventa ×1.25 e ×0.5 diventa ×0.8 (immunità = ×0.6).
 */
export function typeMultiplier(attacker: PokeType[], defender: PokeType[]): number {
  const best = Math.max(...attacker.map((t) => effectiveness(t, defender)));
  if (best === 0) return 0.6;
  return Math.pow(best >= 1 ? 1.25 : 0.8, Math.abs(Math.log2(best)));
}
